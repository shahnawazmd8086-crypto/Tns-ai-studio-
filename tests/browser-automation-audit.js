'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const browser = require('../server/browser/BrowserAutomation');
const server = fs.readFileSync(path.join(__dirname, '..', 'server/server.js'), 'utf8');
assert.equal(browser.validatePublicHttpUrl('https://example.com/path#part'), 'https://example.com/path');
assert.throws(() => browser.validatePublicHttpUrl('file:///etc/passwd'), /HTTP and HTTPS/);
assert.throws(() => browser.validatePublicHttpUrl('http://localhost:3000'), /public websites only/);
assert.throws(() => browser.validatePublicHttpUrl('http://127.0.0.1'), /private or local/);
assert.throws(() => browser.validatePublicHttpUrl('http://192.168.1.2'), /private or local/);
assert.throws(() => browser.validatePublicHttpUrl('https://user:pass@example.com'), /embedded usernames or passwords/);
assert(server.includes("url.pathname === '/api/tns-ai/browser/inspect'"), 'Authenticated website inspection route must exist');
assert(server.includes("url.pathname === '/api/tns-ai/browser/prepare'"), 'Authenticated website preparation route must exist');
assert.equal(typeof browser.inspectInteractiveWebsite, 'function', 'Read-only form preparation adapter must exist');
assert(fs.readFileSync(path.join(__dirname, '..', 'server/browser/BrowserAutomation.js'), 'utf8').includes('read_only_form_preparation'), 'Preparation mode must clearly be read-only');
assert(fs.readFileSync(path.join(__dirname, '..', 'server/browser/BrowserAutomation.js'), 'utf8').includes("el.type !== 'password'") === false, 'Password fields must not be extracted as form values');
assert(server.includes('const user = requireAuth(req, res); if (!user) return;'), 'Browser inspection must require authentication');
assert(server.includes('BrowserAutomation.inspectPublicWebsite(pageUrl)'), 'Browser route must call browser adapter');
console.log('BROWSER_AUTOMATION_AUDIT_OK');
