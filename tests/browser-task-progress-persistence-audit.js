'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tns-task-store-'));
const store = path.join(dir, 'tasks.json');
const modulePath = path.resolve(__dirname, '../server/browser/TaskProgress.js');
const run = (source) => spawnSync(process.execPath, ['-e', source], { encoding: 'utf8', env: { ...process.env, TNS_TASK_PROGRESS_FILE: store } });
const first = run(`const t=require(${JSON.stringify(modulePath)}); const r=t.createTask('user-A',{goal:'Prepare public contact form',steps:[{title:'Review fields',website:'https://example.com'}]}); console.log(r.task.id);`);
assert.equal(first.status, 0, first.stderr);
const taskId = first.stdout.trim().split(/\r?\n/).pop();
assert.ok(fs.existsSync(store), 'task store file should exist');
const second = run(`const t=require(${JSON.stringify(modulePath)}); const r=t.getTask('user-A',${JSON.stringify(taskId)}); console.log(r.task.id); try { t.getTask('user-B',${JSON.stringify(taskId)}); process.exitCode=2; } catch(e) { if(e.statusCode!==403) throw e; }`);
assert.equal(second.status, 0, second.stderr);
assert.equal(second.stdout.trim().split(/\r?\n/).pop(), taskId, 'task should survive module/process restart');
const data = JSON.parse(fs.readFileSync(store, 'utf8'));
assert.equal(data.length, 1);
assert.equal(data[0].userId, 'user-A');
fs.rmSync(dir, { recursive: true, force: true });
console.log('BROWSER_TASK_PROGRESS_PERSISTENCE_AUDIT_OK');
