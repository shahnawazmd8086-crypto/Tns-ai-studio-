const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const js = fs.readFileSync(path.join(root, 'public', 'app.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'public', 'style.css'), 'utf8');
assert(js.includes("shareButton.className = 'home-reply-share-button'"), 'Share icon must be created for TNS replies.');
assert(js.includes("navigator.share({ title: 'TNS Studio', text: textToShare })"), 'Share icon must open the native share sheet with the exact reply text.');
assert(js.includes("const thisReplyOnly = String(replyText ?? '');"), 'Each share button must capture only its own TNS reply text.');
assert(js.includes('const textToShare = thisReplyOnly;'), 'Share action must use the captured reply, not the chat history or neighboring replies.');
assert(!/navigator\.share\([\s\S]{0,180}(?:messages\.innerText|messages\.textContent|conversationHistory)/.test(js), 'Share action must not submit the full conversation.');
assert(js.includes('addReplyShareButton(node, text)'), 'Previously displayed/history TNS replies must receive Share action.');
assert(js.includes('addReplyShareButton(pending, displayedReply)'), 'New TNS replies must receive Share action.');
assert(js.includes("if (error?.name === 'AbortError') return;"), 'Cancelling the share sheet must not show a false error.');
assert(js.includes("setStatus('Is browser mein Share option nahi hai. Jawab copy ho gaya; kisi bhi app mein paste karein.')"), 'Unsupported browsers must provide a copy fallback.');
assert(css.includes('.home-reply-share-button'), 'Share icon styling is missing.');
assert(js.includes("copyButton.className = 'home-reply-copy-button'"), 'Existing Copy action must remain.');
assert(js.includes("playReplyButton.className='home-reply-voice-button'"), 'Existing Voice action must remain.');
