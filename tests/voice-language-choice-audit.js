const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const js=fs.readFileSync(path.join(root,'public','app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'public','index.html'),'utf8');
const voiceOptions=['hi-IN','en-IN','ta-IN','kn-IN','te-IN','bn-IN','gu-IN','pa-IN','ml-IN','mr-IN','ur-IN','or-IN','ar-SA','ru-RU','zh-CN','ja-JP','ko-KR','th-TH','el-GR','he-IL'];
for(const code of voiceOptions) assert(html.includes(`value="${code}"`),`Voice UI must offer ${code}.`);
assert(html.includes('id="voiceLanguage"'),'Voice language selector is required.');
assert(html.includes('id="voiceSystemVoice"'),'Voice UI must expose available device voices.');
assert(html.includes('id="voiceSpeechRate"'),'Voice UI must expose speech speed options.');
assert(js.includes('function selectedVoiceLanguage()'),'Voice language selection helper is required.');
assert(js.includes("recognition.lang=selectedVoiceLanguage();")||js.includes("currentRecognition.lang=selectedVoiceLanguage();"),'Speech recognition must use the selected language.');
assert(js.includes('window.speechSynthesis.getVoices?.()'),'Playback must check available device voices.');
assert(js.includes("localStorage.setItem('tnsVoiceURI',voiceChoiceEl.value)"),'Selected device voice must be remembered.');
assert(js.includes('u.rate=Math.min(2,Math.max(0.5,Number(voiceRateEl?.value||1)))'),'Speech speed must be applied with safe bounds.');
assert(js.includes('u.lang=language;'),'Playback must use the selected language.');
for(const locale of ["mr-IN","ur-IN","or-IN","ar-SA","ru-RU","zh-CN","ja-JP","ko-KR","th-TH","el-GR","he-IL"]) assert(js.includes(locale),`Voice locale mapping must include ${locale}.`);
console.log('VOICE_LANGUAGE_CHOICE_AUDIT_OK');
